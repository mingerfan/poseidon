"""Emit trusted Hecate trace source and its public constant archive."""

import json
from pathlib import Path

import numpy as np

from .base import Backend, BackendError, _Cipher, _Counters, _Plain


class EmitExpr(_Cipher):
    def __init__(self, backend, name, *, is_input=False):
        super().__init__(backend, is_input=is_input)
        self.name = name


class EmitBackend(Backend):
    def __init__(self, slots, *, frontend="/frontend/hecate/expr.py", constants="/out/constants.npz", save_dir="/out"):
        super().__init__(slots)
        self.frontend, self.constants, self.save_dir = str(frontend), str(constants), str(save_dir)
        self._counter = _Counters()
        self._lines = []
        self._defined_constants = set()

    def _make_input(self, index):
        return EmitExpr(self, f"x{index}", is_input=True)

    def _apply(self, kind, left, right=None, *, step=None):
        for value in (left, right):
            if isinstance(value, _Plain) and value.name not in self._defined_constants:
                self._lines.append(f'    {value.name} = hc.Plain(C["{value.name}"])')
                self._defined_constants.add(value.name)
        name = f"t{self._counter.total}"
        if kind in ("add", "sub", "mul_cc", "mul_cp"):
            symbol = {"add": "+", "sub": "-", "mul_cc": "*", "mul_cp": "*"}[kind]
            expression = f"{left.name} {symbol} {right.name}"
        elif kind == "neg":
            expression = f"-{left.name}"
        elif kind == "rot":
            expression = f"{left.name}.rotate({step})"
        elif kind == "boot":
            expression = f"hc.bootstrap({left.name})"
        else:
            raise BackendError(f"Unknown operation {kind}")
        self._lines.append(f"    {name} = {expression}")
        self._counter.record(kind, step)
        return EmitExpr(self, name)

    def stats(self):
        return self._counter.stats(len(self._constants))

    def render(self) -> tuple[str, dict[str, np.ndarray]]:
        if self._outputs is None:
            raise BackendError("Declare outputs before rendering")
        counts = self._counter.counts
        summary = " ".join(f"{key}={counts[key]}" for key in counts) + f" consts={len(self._constants)}"
        inputs = [value.name for value in self._inputs]
        signature = ",".join("c" for _ in inputs)
        outputs = [value.name for value in self._outputs]
        result = outputs[0] if len(outputs) == 1 else "[" + ", ".join(outputs) + "]"
        lines = [
            "# Generated by pt_agent.backends.emit. Trusted lowering output; do not edit.",
            "# ops: " + summary,
            "import importlib.util", "import sys", "import numpy as np",
            '_spec = importlib.util.spec_from_file_location("hecate_expr", ' + json.dumps(self.frontend) + ")",
            "hc = importlib.util.module_from_spec(_spec)",
            "sys.modules[_spec.name] = hc", "_spec.loader.exec_module(hc)",
            "C = np.load(" + json.dumps(self.constants) + ")", "", "",
            "@hc.func(" + json.dumps(signature) + ")", "def golden(" + ", ".join(inputs) + "):",
            *self._lines, "    return " + result, "", "",
            "hc.save(" + json.dumps(self.save_dir) + ", " + json.dumps(self.save_dir) + ")",
        ]
        constants = {value.name: value.data for value in self._constants.values()}
        return "\n".join(lines) + "\n", constants

    def write(self, out_dir):
        text, constants = self.render()
        out_dir = Path(out_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / "candidate_trace.py").write_text(text)
        np.savez(out_dir / "constants.npz", **constants)
