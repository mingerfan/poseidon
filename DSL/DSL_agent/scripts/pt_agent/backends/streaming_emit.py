"""Trusted source emission with streamed, indexed public constant storage.

Dense operands are generated by the original kernels.  Storage preserves their
float64 values and signed zeros while writing only nonzero/signed-zero entries
when that is smaller.  This prepares source artifacts; native tracing and its
own memory use require a separate supervised execution.
"""

import json
from pathlib import Path
import shutil

import numpy as np

from .base import Backend, BackendError, _Counters, _Plain
from .emit import EmitExpr


class ConstantWriter:
    def __init__(self, directory, slots, *, max_bytes=4*1024**3):
        self.directory, self.slots, self.max_bytes = Path(directory), slots, max_bytes
        self.directory.mkdir(parents=True, exist_ok=False)
        self.payload = (self.directory/'constants.data').open('wb')
        self.index = (self.directory/'constants-index.jsonl').open('w')
        self.names = set()
        self.payload_bytes = self.index_bytes = self.logical_bytes = 0
        self.closed = False

    def add(self, name, vector):
        if self.closed:
            raise BackendError('The streaming constant store is closed')
        if name in self.names:
            return
        array = np.asarray(vector)
        if array.dtype != np.float64 or array.shape != (self.slots,) or not np.isfinite(array).all():
            raise BackendError('Streaming constants require a finite float64 slot vector')
        nonzero = np.flatnonzero((array != 0.) | np.signbit(array))
        index_dtype = '<u2' if self.slots <= 65536 else '<u4'
        index_bytes = np.dtype(index_dtype).itemsize
        sparse = len(nonzero)*(8+index_bytes) < array.nbytes
        record = dict(name=name, offset=self.payload_bytes, slots=self.slots,
            encoding='indexed64' if sparse else 'dense64', count=len(nonzero) if sparse else self.slots,
            index_dtype=index_dtype if sparse else None)
        record['nbytes'] = len(nonzero)*(8+index_bytes) if sparse else array.nbytes
        line = json.dumps(record, separators=(',', ':'))+'\n'
        if self.payload_bytes+record['nbytes']+self.index_bytes+len(line.encode()) > self.max_bytes:
            raise BackendError('The streaming constant storage allowance is exhausted')
        if sparse:
            self.payload.write(nonzero.astype(index_dtype).tobytes())
            self.payload.write(array[nonzero].astype('<f8', copy=False).tobytes())
        else:
            self.payload.write(array.astype('<f8', copy=False).tobytes())
        self.index.write(line)
        self.names.add(name)
        self.payload_bytes += record['nbytes']
        self.index_bytes += len(line.encode())
        self.logical_bytes += array.nbytes

    def close(self):
        if not self.closed:
            self.payload.close()
            self.index.close()
            self.closed = True


class ConstantReader:
    def __init__(self, directory):
        self.directory, self.records = Path(directory), {}
        size = (self.directory/'constants.data').stat().st_size
        with (self.directory/'constants-index.jsonl').open() as stream:
            for line in stream:
                record = json.loads(line)
                name = record['name']
                integers = [record[key] for key in ('offset','slots','count','nbytes')]
                if (name in self.records or not isinstance(name,str)
                        or any(type(value) is not int or value < 0 for value in integers)
                        or record['slots'] < 1 or record['count'] > record['slots']
                        or record['offset']+record['nbytes'] > size):
                    raise BackendError('The streaming constant index has invalid dimensions or ranges')
                if record['encoding']=='dense64':
                    expected=record['slots']*8
                    valid=record['count']==record['slots'] and record['index_dtype'] is None
                elif record['encoding']=='indexed64' and record['index_dtype'] in ('<u2','<u4'):
                    expected=record['count']*(8+np.dtype(record['index_dtype']).itemsize)
                    valid=True
                else:
                    raise BackendError('The streaming constant encoding is unsupported')
                if not valid or expected != record['nbytes']:
                    raise BackendError('The streaming constant encoding size differs')
                self.records[name]=record
        self.payload=(self.directory/'constants.data').open('rb')

    def load(self, name):
        record=self.records[name]
        self.payload.seek(record['offset'])
        raw=self.payload.read(record['nbytes'])
        if len(raw) != record['nbytes']:
            raise BackendError('A streaming constant payload is incomplete')
        if record['encoding']=='dense64':
            array=np.frombuffer(raw,dtype='<f8').copy()
        else:
            amount=record['count']*np.dtype(record['index_dtype']).itemsize
            indices=np.frombuffer(raw[:amount],dtype=record['index_dtype'])
            if len(indices) and (int(indices[-1]) >= record['slots'] or np.any(indices[1:] <= indices[:-1])):
                raise BackendError('Streaming constant indices must be ordered unique slot positions')
            array=np.zeros(record['slots'],dtype=np.float64)
            array[indices]=np.frombuffer(raw[amount:],dtype='<f8')
        if not np.isfinite(array).all():
            raise BackendError('The streaming constant payload is nonfinite')
        array.flags.writeable=False
        return array

    def close(self):
        self.payload.close()


class StreamingEmitBackend(Backend):
    _keep_const_data=False

    def __init__(self, slots, *, directory, frontend, max_constant_bytes=4*1024**3):
        super().__init__(slots)
        self.directory, self.frontend = Path(directory), str(frontend)
        self.store=ConstantWriter(self.directory/'constant-store',slots,max_bytes=max_constant_bytes)
        self.body_path=self.directory/'arithmetic.pyfrag'
        self.body=self.body_path.open('w')
        self._counter=_Counters()
        self.finished=False

    def const(self, vector):
        if isinstance(vector,np.ndarray) and not vector.flags.writeable:
            vector=np.array(vector,copy=True)
        return self._const(vector,keep_data=True)

    def _make_input(self,index):
        return EmitExpr(self,f'x{index}',is_input=True)

    def _apply(self,kind,left,right=None,*,step=None):
        if self.finished:
            raise BackendError('The streaming emission is closed')
        for value in (left,right):
            if isinstance(value,_Plain) and value.name not in self.store.names:
                self.store.add(value.name,value.data)
                self.body.write(f'    {value.name} = hc.Plain(C.load("{value.name}"))\n')
        name=f't{self._counter.total}'
        if kind in ('add','sub','mul_cc','mul_cp'):
            symbol={'add':'+','sub':'-','mul_cc':'*','mul_cp':'*'}[kind]
            expression=f'{left.name} {symbol} {right.name}'
        elif kind=='neg':expression=f'-{left.name}'
        elif kind=='rot':expression=f'{left.name}.rotate({step})'
        elif kind=='boot':expression=f'hc.bootstrap({left.name})'
        else:raise BackendError('Unsupported streaming Emit operation: '+kind)
        self.body.write(f'    {name} = {expression}\n')
        self._counter.record(kind,step)
        return EmitExpr(self,name)

    def stats(self):
        result=self._counter.stats(len(self._constants))
        result.update(stored_constants=len(self.store.names),constant_payload_bytes=self.store.payload_bytes,
            constant_index_bytes=self.store.index_bytes,logical_dense_constant_bytes=self.store.logical_bytes,
            retained_constant_arrays=sum(value.data is not None for value in self._constants.values()),
            identity_cache_entries=len(self._constant_objects),native_trace_executions=0,
            native_trace_memory_bytes=None,compiler_runs=0,real_ckks_executions=0)
        return result

    def close(self):
        self.body.close()
        self.store.close()
        self.finished=True

    def write(self):
        if self.finished or self._outputs is None:
            raise BackendError('Declare one final output before a single streaming write')
        self.body.close();self.store.close();self.finished=True
        inputs=[value.name for value in self._inputs]
        outputs=[value.name for value in self._outputs]
        returned=outputs[0] if len(outputs)==1 else '['+', '.join(outputs)+']'
        header=['# Trusted pt_agent streaming lowering output. Native tracing remains a separate stage.',
            'import importlib.util','import sys',
            'from pt_agent.backends.streaming_emit import ConstantReader',
            '_spec = importlib.util.spec_from_file_location("hecate_expr", '+json.dumps(self.frontend)+')',
            'hc = None','C = None','_frontend_loaded = False','_frontend_finalized = False',
            '_save_attempts = 0','_save_completed = False','_finalize_attempts = 0',
            'try:',
            '    hc = importlib.util.module_from_spec(_spec)','    sys.modules[_spec.name] = hc','    _spec.loader.exec_module(hc)',
            '    _frontend_loaded = True',
            '    C = ConstantReader('+json.dumps(str(self.directory/'constant-store'))+')','',
            '    @hc.func('+json.dumps(','.join('c' for _ in inputs))+')',
            '    def golden('+', '.join(inputs)+'):']
        destination=self.directory/'candidate_trace.py'
        with destination.open('w') as stream:
            stream.write('\n'.join(header)+'\n')
            with self.body_path.open() as body:
                for line in body:stream.write('    '+line)
            stream.write('        return '+returned+'\n\n')
            stream.write('    _save_attempts += 1\n')
            stream.write('    _saved_mlir = hc.save('+json.dumps(str(self.directory))+', '+json.dumps(str(self.directory))+')\n')
            stream.write('    _save_completed = True\n')
            stream.write('finally:\n    if C is not None:\n        C.close()\n')
            stream.write('    if _frontend_loaded and getattr(hc, "ctxt", None):\n')
            stream.write('        _finalize_attempts += 1\n        hc.lt.finalize(hc.ctxt)\n        _frontend_finalized = True\n')
        return destination
