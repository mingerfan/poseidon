import ast
import os
from pathlib import Path
import subprocess
import sys
from tempfile import TemporaryDirectory
import unittest

import numpy as np

from pt_agent.backends import BackendError, EmitBackend, run_program
from pt_agent.tests.test_r2_backends import PROGRAMS, SLOTS, count_run, inputs, mock_run, reverse_program


FIXTURE = Path(__file__).resolve().parent / "fixtures/fake_hecate_expr.py"
EXPECTED = '''# Generated by pt_agent.backends.emit. Trusted lowering output; do not edit.
# ops: add=1 sub=0 neg=0 mul_cc=0 mul_cp=1 rot=1 boot=0 consts=1
import importlib.util
import sys
import numpy as np
_spec = importlib.util.spec_from_file_location("hecate_expr", "/frontend/hecate/expr.py")
hc = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = hc
_spec.loader.exec_module(hc)
C = np.load("/out/constants.npz")


@hc.func("c")
def golden(x0):
    k0 = hc.Plain(C["k0"])
    t0 = x0 * k0
    t1 = x0.rotate(1)
    t2 = t0 + t1
    return t2


hc.save("/out", "/out")
'''


class EmitTests(unittest.TestCase):
    def test_exact_text_and_constant(self):
        backend = EmitBackend(4)
        with self.assertRaises(BackendError):
            backend.render()
        run_program(backend, lambda b, x: x*2.0 + x.rotate(1), 1)
        text, constants = backend.render()
        self.assertEqual(text, EXPECTED)
        self.assertEqual(list(constants), ["k0"])
        self.assertTrue(np.array_equal(constants["k0"], np.full(4, 2.0)))

    def check_emitted(self, fn, n):
        values = inputs(n)
        mock = mock_run(fn, values)
        counter = count_run(fn, n)
        with TemporaryDirectory() as directory:
            directory = Path(directory)
            backend = EmitBackend(SLOTS, frontend=str(FIXTURE), constants=str(directory / "constants.npz"),
                                  save_dir=str(directory))
            run_program(backend, fn, n)
            for key in ("counts", "ops_total", "distinct_consts"):
                self.assertEqual(backend.stats()[key], counter.stats()[key])
            backend.write(directory)
            np.savez(directory / "inputs.npz", **{f"x{i}": x for i, x in enumerate(values)})
            result = subprocess.run([sys.executable, "-B", str(directory / "candidate_trace.py")],
                                    env={**os.environ, "FAKE_HECATE_INPUTS": str(directory / "inputs.npz")},
                                    capture_output=True, text=True, timeout=15)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            with np.load(directory / "fake_outputs.npz") as output:
                self.assertEqual(len(output.files), len(mock.outputs))
                for i, expected in enumerate(mock.outputs):
                    self.assertTrue(np.array_equal(output[f"o{i}"], expected))
            if fn.__name__ in ("p3", "p4", "p5"):
                with np.load(directory / "constants.npz") as constants:
                    self.assertEqual(constants.files, [])

    def test_p1_to_p5_count_and_fake_execution(self):
        for name, fn, n in PROGRAMS:
            with self.subTest(program=name):
                self.check_emitted(fn, n)

    def test_reverse_arithmetic_and_negation(self):
        self.check_emitted(reverse_program, 1)

    def test_allowed_imports_and_source(self):
        for name, fn, n in PROGRAMS:
            with self.subTest(program=name):
                backend = EmitBackend(SLOTS)
                run_program(backend, fn, n)
                text, _ = backend.render()
                for forbidden in ("exec(", "eval(", "__import__"):
                    self.assertNotIn(forbidden, text)
                tree = ast.parse(text)
                self.assertTrue(all(node.lineno <= 5 for node in ast.walk(tree)
                                    if isinstance(node, (ast.Import, ast.ImportFrom))))

    def test_golden_body_is_straight_line(self):
        for name, fn, n in PROGRAMS:
            with self.subTest(program=name):
                backend = EmitBackend(SLOTS)
                run_program(backend, fn, n)
                tree = ast.parse(backend.render()[0])
                golden = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == "golden")
                self.assertIsInstance(golden.body[-1], ast.Return)
                self.assertTrue(all(isinstance(node, ast.Assign) for node in golden.body[:-1]))
